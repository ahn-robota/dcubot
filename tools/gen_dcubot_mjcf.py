"""Generate playground/dcubot/xmls/dcubot.xml from the Placo-verified dcubot URDF
(0918b CAD: hips separated along Y, forward = +X, mirrored joint-axis signs).

Follows the conventions of the previous 0913 MJCF (kept in xmls_0913_archive/):
freejoint 'base' wrapper, base_link root inertial, only the two feet collide,
STS3215 position actuators, IMU/foot sensors.
"""
import sys
import xml.etree.ElementTree as ET

URDF = sys.argv[1]
OUT = sys.argv[2]

root = ET.parse(URDF).getroot()
links, joints = {}, {}
for l in root.findall("link"):
    name = l.get("name")
    inr = l.find("inertial")
    vis = l.find("visual")
    links[name] = {
        "inertial": None if inr is None else {
            "pos": inr.find("origin").get("xyz"),
            "mass": inr.find("mass").get("value"),
            "I": inr.find("inertia").attrib,
        },
        "vis_pos": None if vis is None else vis.find("origin").get("xyz"),
        "mesh": None if vis is None else vis.find("geometry/mesh").get("filename").split("/")[-1],
    }
for j in root.findall("joint"):
    if j.get("type") != "revolute":
        continue
    lim = j.find("limit")
    joints[j.get("name")] = {
        "parent": j.find("parent").get("link"),
        "child": j.find("child").get("link"),
        "pos": j.find("origin").get("xyz"),
        "axis": j.find("axis").get("xyz"),
        "lo": lim.get("lower"), "hi": lim.get("upper"),
    }

children = {}
for n, j in joints.items():
    children.setdefault(j["parent"], []).append(n)
ORDER = ["left_hip_yaw", "left_hip_roll", "left_hip_pitch", "left_knee", "left_ankle",
         "right_hip_yaw", "right_hip_roll", "right_hip_pitch", "right_knee", "right_ankle",
         "neck_pitch", "head_pitch", "head_yaw"]

def fmt(xyz):
    return " ".join(f"{float(v):.6g}" for v in xyz.split())

def inertial_xml(l, ind):
    i = l["inertial"]
    I = i["I"]
    full = " ".join(f"{float(I[k]):.6g}" for k in ("ixx", "iyy", "izz", "ixy", "ixz", "iyz"))
    return f'{ind}<inertial pos="{fmt(i["pos"])}" mass="{float(i["mass"]):.8g}" fullinertia="{full}"/>\n'

def body_xml(jn, ind):
    j = joints[jn]
    l = links[j["child"]]
    s = f'{ind}<body name="{j["child"]}" pos="{fmt(j["pos"])}">\n'
    s += inertial_xml(l, ind + "  ")
    s += (f'{ind}  <joint name="{jn}" type="hinge" axis="{fmt(j["axis"])}" '
          f'range="{float(j["lo"]):.7g} {float(j["hi"]):.7g}" class="sts3215"/>\n')
    is_foot = jn.endswith("_ankle")
    side = "left" if jn.startswith("left") else "right"
    if is_foot:
        s += (f'{ind}  <geom name="{side}_foot_collision" pos="{fmt(l["vis_pos"])}" type="mesh" '
              f'rgba="0.7 0.7 0.7 1" mesh="{j["child"]}"/>\n')
        s += f'{ind}  <!-- PLACEHOLDER: body-origin foot site, not the true sole/ground contact point -->\n'
        s += f'{ind}  <site name="{side}_foot" pos="0 0 0"/>\n'
    else:
        s += (f'{ind}  <geom class="sts3215" pos="{fmt(l["vis_pos"])}" type="mesh" '
              f'rgba="0.7 0.7 0.7 1" mesh="{j["child"]}"/>\n')
    for c in sorted(children.get(j["child"], []), key=ORDER.index):
        s += body_xml(c, ind + "  ")
    s += f"{ind}</body>\n"
    return s

base = links["base_link"]
mesh_names = [l for l in links if links[l]["mesh"]]
assets = "".join(
    f'    <mesh name="{n}" file="{links[n]["mesh"]}" scale="0.001 0.001 0.001"/>\n' for n in mesh_names)
bi = base["inertial"]
imu = fmt(bi["pos"])
top = sorted(children["base_link"], key=ORDER.index)
bodies = "".join(body_xml(c, "        ") for c in top)

xml = f'''<?xml version="1.0"?>
<!-- Generated by tools/gen_dcubot_mjcf.py from the Placo-verified 0918b URDF
     (hips along Y, forward = +X). The previous 0913 model is in xmls_0913_archive/. -->
<mujoco model="dcubot">

  <option iterations="1" ls_iterations="5">
    <flag eulerdamp="disable"/>
  </option>
  <compiler angle="radian" meshdir="assets"/>

  <default>
    <default class="dcubot">
      <joint frictionloss="0.1" armature="0.005"/>
      <position kp="50" dampratio="1"/>
    </default>
  </default>

  <sensor>
    <gyro site="imu" name="gyro"/>
    <velocimeter site="imu" name="local_linvel"/>
    <accelerometer site="imu" name="accelerometer"/>
    <framezaxis objtype="site" objname="imu" name="upvector"/>
    <framexaxis objtype="site" objname="imu" name="forwardvector"/>
    <framelinvel objtype="site" objname="imu" name="global_linvel"/>
    <frameangvel objtype="site" objname="imu" name="global_angvel"/>
    <framepos objtype="site" objname="imu" name="position"/>
    <framequat objtype="site" objname="imu" name="orientation"/>
    <framelinvel objtype="site" objname="right_foot" name="right_foot_global_linvel"/>
    <framelinvel objtype="site" objname="left_foot" name="left_foot_global_linvel"/>
    <framexaxis objtype="site" objname="left_foot" name="left_foot_upvector"/>
    <framexaxis objtype="site" objname="right_foot" name="right_foot_upvector"/>
    <framepos objtype="site" objname="left_foot" name="left_foot_pos"/>
    <framepos objtype="site" objname="right_foot" name="right_foot_pos"/>
  </sensor>

  <default>
    <default class="sts3215">
      <geom contype="0" conaffinity="0"/>
      <joint damping="0.56" frictionloss="0.068" armature="0.027"/>
      <position kp="13.37" kv="0.0" forcerange="-3.23 3.23"/>
    </default>
    <default class="backlash">
      <joint damping="0.01" frictionloss="0" armature="0.01" limited="true"
        range="-0.008726646259971648 0.008726646259971648"/>
    </default>
  </default>

  <asset>
{assets}  </asset>

  <worldbody>
    <body name="base" pos="0 0 0.21">
      <freejoint name="dcubot_freejoint"/>
      <!-- PLACEHOLDER: real IMU mount not finalized; at base_link's COM for now. -->
      <site name="imu" pos="{imu}"/>

      <body name="base_link" childclass="dcubot">
        <!-- root inertial kept explicitly (MuJoCo's URDF import drops it for the world-welded root) -->
{inertial_xml(base, "        ")}        <geom class="sts3215" type="mesh" rgba="0.7 0.7 0.7 1" mesh="base_link"/>

{bodies}      </body>
    </body>
  </worldbody>

  <actuator>
''' + "".join(f'    <position class="sts3215" name="{n}" joint="{n}" inheritrange="1"/>\n' for n in ORDER) + '''  </actuator>
  <equality/>
</mujoco>
'''
open(OUT, "w").write(xml)
print("wrote", OUT, "| joints:", len(joints), "| meshes:", len(mesh_names))
